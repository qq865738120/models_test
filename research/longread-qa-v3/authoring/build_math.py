def add(phase, id, stem, refs, options, derivation, claim_scope):
    assert len(options) == 6 and len(set(text for _, text, _ in options)) == 6
    q = {'id': id, 'domain': 'math', 'question': '【多选；须选全，漏选或多选均不得分】' + stem,
         'options': {k: t for k, (_, t, _) in zip(LETTERS, options)},
         'multiple': True, 'weight': (2 if phase == 'initial' and int(id[1:]) <= 9 else
                                      1 if phase == 'initial' else
                                      5 if id == 'XM01' else 4), 'scoring': 'exact'}
    evi = [copy.deepcopy(E[r]) for r in refs]
    ans = ''.join(k for k, (ok, _, _) in zip(LETTERS, options) if ok)
    assert ans and ans != LETTERS
    a = {'id': id, 'answer': ans, 'evidence': evi,
         'optionAudit': {k: {'correct': ok, 'credit': int(ok), 'reason': reason,
                             'evidence': copy.deepcopy(evi), 'claimType': 'derivedFromSourceClaims'}
                         for k, (ok, _, reason) in zip(LETTERS, options)},
         'derivation': derivation, 'claimScope': claim_scope}
    questions[phase].append(q)
    answers[phase].append(a)


