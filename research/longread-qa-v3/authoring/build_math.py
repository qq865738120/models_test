def ev(src, needle='Abstract', length=1250, note='原文所述结论及其适用范围。'):
    path = FILES[src]
    data = path.read_text(encoding='utf-8')
    at = data.find(needle)
    if at < 0:
        raise ValueError((src, needle))
    page = data[:at].count('[PDF page ')
    quote = data[at:at + length]
    quote = quote.split('[PDF page ')[0]
    return dict(source=src, path=path.relative_to(ROOT).as_posix(),
                locator=f'PDF p.{page}; TXT near {needle[:35]}', quote=quote,
                note=note, claimType='sourceClaim')


