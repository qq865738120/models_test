    import copy
    for task in tasks:
        task['promptVersion'] = PROMPT_VERSION
        task['scoringGuidance'] = SCORING_GUIDANCE
        for dimension in task['rubric']:
            dimension['checks'] = CHECKS[task['id']][dimension['id']]
            mid, full = dimension['anchors'][1]['text'], dimension['anchors'][2]['text']
            low, mid, near = ANCHORS[task['id']][dimension['id']]
            dimension['anchors'] = [
                {'score':0,'text':'该维度未实现、完全不可用，或实际核验没有任何成立项。'},
                {'score':2,'text':low},
                {'score':5,'text':mid},
                {'score':8,'text':near},
                {'score':10,'text':full + ' 所列检查全部满足，相关结果可复查。'},
            ]
        task['rubricChange'] = copy.deepcopy(task['rubric'])
        for dimension in task['rubricChange']:
            dimension['checks'] = CHANGE_CHECKS[task['id']][dimension['id']]
            dimension['description'] = '检查追加要求在' + dimension['name'] + '方面的实现及原有行为回归。'
            for index, text in zip((1, 2, 3), CHANGE_ANCHORS[task['id']][dimension['id']]):
                dimension['anchors'][index]['text'] = text
            dimension['anchors'][4]['text'] = '本维度所列追加检查全部满足，涉及的原有行为没有回归，结果可复查。'
